// src/hooks/useSession.js
import { useEffect, useRef, useState } from 'react';

// Создаем кастомный хук useSession
// Это обычная функция но по соглашению имена кастомных хуков начинаются с use
// Это помогает React и линтерам понять что это хук и применить к нему правила хуков
const useSession = () => {
  // Создаем состояние для отслеживания статуса сессии
  // useState возвращает массив из двух элементов первый это текущее значение второй это функция для его изменения
  // Мы используем деструктуризацию массива чтобы получить эти два элемента
  // Начальное значение это строка 'idle' что означает что сессия не активна
  const [sessionStatus, setSessionStatus] = useState('idle');
  // Возможные значения sessionStatus:
  // 'idle' - нет активной сессии, пользователь может начать новую
  // 'active' - сессия идет, таймер тикает
  // 'paused' - сессия приостановлена пользователь может возобновить или завершить
  // 'completed' - сессия успешно завершена пользователь дошел до конца

  // Создаем состояние для хранения продолжительности сессии в секундах
  // По умолчанию это 25 минут умноженные на 60 секунд что дает 1500 секунд
  // Это стандартная длительность по технике Помодоро
  const [duration, setDuration] = useState(25 * 60);

  // Создаем состояние для отслеживания оставшегося времени в секундах
  // Изначально оставшееся время равно полной продолжительности
  // Это значение будет уменьшаться каждую секунду когда сессия активна
  const [remainingTime, setRemainingTime] = useState(duration);

  // Создаем ref для хранения идентификатора интервала таймера
  // useRef создает объект который сохраняется между рендерами но не вызывает перерисовку при изменении
  // Это идеально для хранения идентификатора setInterval потому что нам не нужно перерисовывать компонент когда мы его сохраняем
  // Начальное значение null потому что изначально таймер не запущен
  const timerRef = useRef(null);

  // Функция для запуска новой сессии
  // Эта функция будет вызываться когда пользователь нажимает кнопку начать сессию
  const startSession = (customDuration) => {
    // Если пользователь передал кастомную продолжительность используем её
    // Иначе используем текущее значение duration из состояния
    const sessionDuration = customDuration || duration;

    // Обновляем продолжительность сессии если она была изменена
    setDuration(sessionDuration);

    // Устанавливаем оставшееся время равным полной продолжительности
    // Это сбрасывает таймер к началу для новой сессии
    setRemainingTime(sessionDuration);

    // Меняем статус сессии на активный
    // Это вызовет перерисовку компонента и запустит useEffect который запускает таймер
    setSessionStatus('active');
  };

  // Функция для паузы активной сессии
  // Это позволит пользователю временно остановить таймер не теряя прогресс
  const pauseSession = () => {
    // Меняем статус на приостановлено
    // useEffect увидит это изменение и остановит таймер
    setSessionStatus('paused');
  };

  // Функция для возобновления приостановленной сессии
  // Таймер продолжит отсчет с того места где остановился
  const resumeSession = () => {
    // Меняем статус обратно на активный
    // useEffect увидит это и снова запустит таймер
    setSessionStatus('active');
  };

  // Функция для завершения сессии досрочно
  // Пользователь может захотеть завершить сессию не дожидаясь конца таймера
  const endSession = () => {
    // Меняем статус на idle что означает отсутствие активной сессии
    setSessionStatus('idle');

    // Сбрасываем оставшееся время к полной продолжительности
    // Это подготовит таймер для следующей сессии
    setRemainingTime(duration);
  };

  // Используем useEffect для управления таймером обратного отсчета
  // useEffect запускается после каждого рендера компонента
  // Мы передаем массив зависимостей как второй аргумент чтобы контролировать когда эффект перезапускается
  useEffect(() => {
    // Проверяем активна ли сессия сейчас
    // Таймер должен работать только когда статус active
    if (sessionStatus === 'active') {
      // Запускаем интервал который выполняется каждую секунду то есть каждые 1000 миллисекунд
      // setInterval возвращает идентификатор интервала который мы сохраняем в ref
      // Это позволит нам остановить интервал позже когда это понадобится
      timerRef.current = setInterval(() => {
        // Эта функция выполняется каждую секунду пока интервал активен
        // Мы используем функциональную форму setState чтобы получить актуальное значение
        // Это важно потому что setInterval создает замыкание и может захватить устаревшее значение
        setRemainingTime((prevTime) => {
          // prevTime это текущее оставшееся время на момент вызова

          // Проверяем не закончилось ли время
          // Если осталась одна секунда или меньше значит сессия завершается
          if (prevTime <= 1) {
            // Меняем статус на completed чтобы показать что сессия успешно завершена
            setSessionStatus('completed');

            // Возвращаем 0 чтобы таймер показывал ноль
            return 0;
          }

          // Если время еще осталось уменьшаем его на одну секунду
          return prevTime - 1;
        });
      }, 1000);
    }

    // Функция очистки которая вызывается когда эффект размонтируется или перезапускается
    // Это критически важно для предотвращения утечек памяти
    // Каждый раз когда мы создаем таймер или подписку мы должны её очищать
    return () => {
      // Проверяем существует ли активный интервал
      // Это может быть null если таймер не был запущен
      if (timerRef.current) {
        // Останавливаем интервал чтобы он перестал выполняться
        clearInterval(timerRef.current);

        // Обнуляем ref чтобы показать что интервал больше не активен
        timerRef.current = null;
      }
    };
  }, [sessionStatus]);
  // Массив зависимостей содержит только sessionStatus
  // Это означает что эффект перезапустится только когда изменится sessionStatus
  // Когда статус меняется на active таймер запускается
  // Когда статус меняется на paused или idle таймер останавливается через функцию очистки

  // Возвращаем объект с данными и функциями которые компонент может использовать
  // Это публичный API нашего хука то что будет доступно компонентам
  return {
    // Данные о текущем состоянии сессии
    sessionStatus, // Текущий статус сессии idle active paused или completed
    duration, // Полная продолжительность сессии в секундах
    remainingTime, // Оставшееся время в секундах

    // Функции для управления сессией
    startSession, // Запустить новую сессию
    pauseSession, // Приостановить активную сессию
    resumeSession, // Возобновить приостановленную сессию
    endSession, // Завершить сессию досрочно
  };
};

// Экспортируем хук чтобы его можно было импортировать в компонентах
export default useSession;
